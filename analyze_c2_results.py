"""Merge split C2 copy-safe gate server results.

The C2 server plan splits seeds across CUDA2 and CUDA3. Each lane writes one
`diagnose_repair_loss.py` JSON. This script concatenates the raw per-seed metric
lists, recomputes aggregate means/stds, and writes a single summary artifact.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np


ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results"
OUT_TEX = ROOT / "paper" / "tables" / "c2_copy_safe_numbers.tex"
MODEL_LABEL = "DeltaNAR+copy-safe"

METRICS = [
    "node_acc_v",
    "graph_acc_v",
    "changed_output_acc_v",
    "copy_critical_acc_v",
    "pure_copy_changed_acc_v",
    "gate_recall",
    "copy_critical_gate_recall",
    "changed_output_fraction",
    "copy_critical_fraction",
]


def load_json(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def merge_raw(parts: list[dict]) -> dict:
    merged: dict = {}
    for part in parts:
        for task, by_size in part["raw"].items():
            task_out = merged.setdefault(task, {})
            for size, by_metric in by_size.items():
                size_out = task_out.setdefault(size, {})
                for metric, values in by_metric.items():
                    size_out.setdefault(metric, []).extend(values)
    return merged


def aggregate(raw: dict) -> dict:
    agg = {}
    for task, by_size in raw.items():
        agg[task] = {MODEL_LABEL: {}}
        for size, by_metric in by_size.items():
            agg[task][MODEL_LABEL][size] = {
                metric: [float(np.mean(values)), float(np.std(values))]
                for metric, values in by_metric.items()
            }
    return agg


def pm(pair: list[float]) -> str:
    return f"{pair[0]:.3f} +/- {pair[1]:.3f}"


def tex_pm(pair: list[float]) -> str:
    return f"{pair[0]:.3f} $\\pm$ {pair[1]:.3f}"


def display_source(path: Path) -> str:
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return path.name


def write_markdown(path: Path, sources: list[Path], agg: dict) -> None:
    lines = [
        "# C2 Copy-Safe Gate Server Summary\n",
        "Merged C2 copy-safe gate rerun. This is intended to validate whether the "
        "local AHR copy-safe gate candidate survives a larger 20-seed server "
        "rerun before being promoted into the main paper.\n",
        "## Sources\n",
    ]
    lines.extend(f"- `{display_source(p)}`" for p in sources)
    lines.append("")
    for task, by_model in agg.items():
        lines.append(f"## {task}\n")
        by_size = by_model[MODEL_LABEL]
        sizes = sorted(by_size, key=lambda x: int(x))
        for metric in METRICS:
            if any(metric in by_size[size] for size in sizes):
                lines.append(f"### {metric}\n")
                lines.append("| Model | " + " | ".join(f"n={size}" for size in sizes) + " |")
                lines.append("|---|" + "|".join("---:" for _ in sizes) + "|")
                cells = [pm(by_size[size][metric]) if metric in by_size[size] else "-" for size in sizes]
                lines.append(f"| {MODEL_LABEL} | " + " | ".join(cells) + " |")
                lines.append("")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_tex(path: Path, agg: dict) -> None:
    rows = []
    task_labels = {"sssp": "SSSP", "bottleneck": "Bottleneck"}
    metrics = [
        ("node_acc_v", "node"),
        ("graph_acc_v", "graph"),
        ("changed_output_acc_v", "changed"),
        ("copy_critical_acc_v", "copy-critical"),
        ("gate_recall", "gate recall"),
    ]
    for task in ["sssp", "bottleneck"]:
        by_size = agg[task][MODEL_LABEL]
        for size in ["16", "32", "64", "128"]:
            cells = [task_labels[task], size]
            cells.extend(tex_pm(by_size[size][metric]) for metric, _ in metrics)
            rows.append(cells)

    lines = [
        "% Auto-generated by analyze_c2_results.py; do not edit numbers by hand.",
        r"\newcommand{\CtwoCopySafeRows}{%",
    ]
    for row in rows:
        lines.append(" & ".join(row) + r" \\")
    lines.append("}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--inputs",
        nargs="+",
        default=[
            "results/C2_copysafe_gpu2_seed0_9.json",
            "results/C2_copysafe_gpu3_seed10_19.json",
        ],
    )
    ap.add_argument("--out", default="results/C2_copysafe_20seed_merged.json")
    ap.add_argument("--markdown", default="C2_COPYSAFE_SERVER_SUMMARY.md")
    args = ap.parse_args()

    inputs = [Path(p) if Path(p).is_absolute() else ROOT / p for p in args.inputs]
    parts = [load_json(p) for p in inputs]
    raw = merge_raw(parts)
    agg = aggregate(raw)

    out = Path(args.out) if Path(args.out).is_absolute() else ROOT / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        json.dumps({"sources": [display_source(p) for p in inputs], "agg": agg, "raw": raw}, indent=2),
        encoding="utf-8",
    )

    md = Path(args.markdown) if Path(args.markdown).is_absolute() else ROOT / args.markdown
    write_markdown(md, inputs, agg)
    write_tex(OUT_TEX, agg)
    print(f"wrote {out}")
    print(f"wrote {md}")
    print(f"wrote {OUT_TEX}")


if __name__ == "__main__":
    main()
