"""Summarize server-side B-line experiment results.

The B-line scripts intentionally mix ordinary CLRS-style metrics with
diagnostic slices such as changed-output and copy-critical accuracy. This
script keeps the paper numbers reproducible by deriving the Markdown summary
and LaTeX snippets directly from the JSON files under results/.
"""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results"
OUT_MD = ROOT / "B_RESULTS_SERVER_SUMMARY.md"
OUT_TEX = ROOT / "paper" / "tables" / "b_server_numbers.tex"


MODEL_LABEL = {
    "DeltaNAR": r"\deltanar",
    "no-copy": "no-copy",
    "Naive-d": "Prev+Delta",
    "Recomp+gate": "Recomp+gate",
    "Recompute": "Recompute",
    "Attn": "Attn",
    "Triplet": "Triplet",
    "raw_no_copy": "raw no-copy",
    "predicted_copy": "predicted copy",
    "oracle_affected_copy": "oracle affected copy",
    "oracle_copy_safe_upper": "oracle copy-safe upper",
    "pure_copy": "pure copy",
}


def load(name: str) -> dict:
    with (RESULTS / name).open("r", encoding="utf-8") as f:
        data = json.load(f)
    return data["agg"] if "agg" in data else data


def mean(data: dict, task: str, model: str, size: int, metric: str) -> float | None:
    try:
        val = data[task][model][str(size)][metric]
    except KeyError:
        return None
    if isinstance(val, list):
        return float(val[0])
    if isinstance(val, dict):
        return float(val.get("mean", val.get("value")))
    return float(val)


def std(data: dict, task: str, model: str, size: int, metric: str) -> float | None:
    try:
        val = data[task][model][str(size)][metric]
    except KeyError:
        return None
    if isinstance(val, list) and len(val) > 1:
        return float(val[1])
    if isinstance(val, dict):
        return float(val.get("std", val.get("stderr", 0.0)))
    return 0.0


def pm(data: dict, task: str, model: str, size: int, metric: str) -> str:
    m = mean(data, task, model, size, metric)
    s = std(data, task, model, size, metric)
    if m is None:
        return "--"
    if s is None:
        return f"{m:.3f}"
    return f"{m:.3f} $\\pm$ {s:.3f}"


def md_pm(data: dict, task: str, model: str, size: int, metric: str) -> str:
    m = mean(data, task, model, size, metric)
    s = std(data, task, model, size, metric)
    if m is None:
        return "--"
    if s is None:
        return f"{m:.3f}"
    return f"{m:.3f} +/- {s:.3f}"


def md_table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |"]
    lines.append("| " + " | ".join(["---"] * len(headers)) + " |")
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return "\n".join(lines)


def latex_rows(rows: list[list[str]]) -> str:
    return "\n".join(" & ".join(row) + r" \\" for row in rows)


def build() -> tuple[str, str]:
    b11 = load("B11_main_deltanar_20seed.json")
    b01 = load("B01_sssp_k1_core_diag.json")
    b03 = load("B03_bottleneck_k1_core_diag.json")
    b07 = load("B07_sssp_k8_core_diag.json")
    b08 = load("B08_bottleneck_k4_core_diag.json")
    b02 = load("B02_sssp_triplet_diag.json")
    b09 = load("B09_bottleneck_triplet_diag.json")
    b10 = load("B10_oracle_sssp_bottleneck.json")
    b04 = load("B04_ood_topology_ba_sssp.json")
    b05 = load("B05_ood_weight_wide_sssp.json")
    b06 = load("B06_sssp_extreme_512.json")
    b12 = load("B12_ood_failure_sssp_bottleneck.json")
    b13 = load("B13_bottleneck_extreme_512_1024.json")

    md: list[str] = []
    tex: list[str] = [
        "% Auto-generated by analyze_b_results.py; do not edit numbers by hand.",
    ]

    md.append("# B-Line Server Results Summary\n")
    md.append(
        "Source package: `NAR_B_results_20260606_112149.tar.gz`. "
        "All B01--B13 JSON files were copied into `results/` and parsed from the "
        "server aggregate metrics.\n"
    )

    main_rows_md: list[list[str]] = []
    main_rows_tex: list[list[str]] = []
    for task, label in [("sssp", "SSSP"), ("bottleneck", "Bottleneck")]:
        for n in [16, 32, 64, 128, 256]:
            main_rows_md.append(
                [
                    label,
                    str(n),
                    md_pm(b11, task, "DeltaNAR", n, "node_acc_v"),
                    md_pm(b11, task, "DeltaNAR", n, "graph_acc_v"),
                    md_pm(b11, task, "DeltaNAR", n, "aff_f1"),
                ]
            )
            main_rows_tex.append(
                [
                    label,
                    str(n),
                    pm(b11, task, "DeltaNAR", n, "node_acc_v"),
                    pm(b11, task, "DeltaNAR", n, "graph_acc_v"),
                    pm(b11, task, "DeltaNAR", n, "aff_f1"),
                ]
            )
    md.append("## Main 20-Seed DeltaNAR Grid\n")
    md.append(md_table(["Task", "n", "node_acc_v", "graph_acc_v", "aff_f1"], main_rows_md))
    md.append("")
    tex.append(r"\newcommand{\BServerMainRows}{%")
    tex.append(latex_rows(main_rows_tex))
    tex.append("}")

    hard_specs = [
        ("SSSP k=1", b01, "sssp", 256),
        ("SSSP k=8", b07, "sssp", 256),
        ("Bottleneck k=1", b03, "bottleneck", 256),
        ("Bottleneck k=4", b08, "bottleneck", 256),
    ]
    hard_rows_md: list[list[str]] = []
    hard_rows_tex: list[list[str]] = []
    for setting, data, task, n in hard_specs:
        for model in ["DeltaNAR", "no-copy", "Naive-d", "Recomp+gate", "Recompute", "Attn"]:
            if model not in data.get(task, {}):
                continue
            row_md = [
                setting,
                MODEL_LABEL[model].replace(r"\deltanar", "DeltaNAR"),
                md_pm(data, task, model, n, "node_acc_v"),
                md_pm(data, task, model, n, "graph_acc_v"),
                md_pm(data, task, model, n, "changed_output_acc_v"),
                md_pm(data, task, model, n, "copy_critical_acc_v"),
                md_pm(data, task, model, n, "pure_copy_changed_acc_v"),
            ]
            hard_rows_md.append(row_md)
            hard_rows_tex.append(
                [
                    setting,
                    MODEL_LABEL[model],
                    pm(data, task, model, n, "node_acc_v"),
                    pm(data, task, model, n, "graph_acc_v"),
                    pm(data, task, model, n, "changed_output_acc_v"),
                    pm(data, task, model, n, "copy_critical_acc_v"),
                ]
            )
    md.append("## Diagnostic Slices at n=256\n")
    md.append(
        md_table(
            ["Setting", "Model", "node", "graph", "changed", "copy-critical", "pure-copy changed"],
            hard_rows_md,
        )
    )
    md.append("")
    tex.append(r"\newcommand{\BServerDiagnosticRows}{%")
    tex.append(latex_rows(hard_rows_tex))
    tex.append("}")

    triplet_rows_md: list[list[str]] = []
    triplet_rows_tex: list[list[str]] = []
    for setting, data, task in [("SSSP", b02, "sssp"), ("Bottleneck", b09, "bottleneck")]:
        for n in [16, 32, 64]:
            triplet_rows_md.append(
                [
                    setting,
                    str(n),
                    md_pm(data, task, "Triplet", n, "node_acc_v"),
                    md_pm(data, task, "Triplet", n, "graph_acc_v"),
                    md_pm(data, task, "Triplet", n, "changed_output_acc_v"),
                    md_pm(data, task, "Triplet", n, "copy_critical_acc_v"),
                ]
            )
            triplet_rows_tex.append(
                [
                    setting,
                    str(n),
                    pm(data, task, "Triplet", n, "node_acc_v"),
                    pm(data, task, "Triplet", n, "graph_acc_v"),
                    pm(data, task, "Triplet", n, "changed_output_acc_v"),
                    pm(data, task, "Triplet", n, "copy_critical_acc_v"),
                ]
            )
    md.append("## Triplet Diagnostic Baseline\n")
    md.append(md_table(["Task", "n", "node", "graph", "changed", "copy-critical"], triplet_rows_md))
    md.append("")
    tex.append(r"\newcommand{\BServerTripletRows}{%")
    tex.append(latex_rows(triplet_rows_tex))
    tex.append("}")

    oracle_rows_md: list[list[str]] = []
    oracle_rows_tex: list[list[str]] = []
    for task, label in [("sssp", "SSSP"), ("bottleneck", "Bottleneck")]:
        for n in [64, 128]:
            for model in [
                "raw_no_copy",
                "predicted_copy",
                "oracle_affected_copy",
                "oracle_copy_safe_upper",
                "pure_copy",
            ]:
                oracle_rows_md.append(
                    [
                        label,
                        str(n),
                        MODEL_LABEL[model],
                        md_pm(b10, task, model, n, "node_acc_v"),
                        md_pm(b10, task, model, n, "changed_output_acc_v"),
                        md_pm(b10, task, model, n, "copy_critical_acc_v"),
                    ]
                )
                oracle_rows_tex.append(
                    [
                        label,
                        str(n),
                        MODEL_LABEL[model],
                        pm(b10, task, model, n, "node_acc_v"),
                        pm(b10, task, model, n, "changed_output_acc_v"),
                        pm(b10, task, model, n, "copy_critical_acc_v"),
                    ]
                )
    md.append("## Copy Oracle Study\n")
    md.append(md_table(["Task", "n", "Variant", "node", "changed", "copy-critical"], oracle_rows_md))
    md.append("")
    tex.append(r"\newcommand{\BServerOracleRows}{%")
    tex.append(latex_rows(oracle_rows_tex))
    tex.append("}")

    ood_rows_md: list[list[str]] = []
    ood_rows_tex: list[list[str]] = []
    for setting, data, task, n in [
        ("BA topology SSSP", b04, "sssp", 64),
        ("Wide-weight SSSP", b05, "sssp", 64),
        ("Failure SSSP", b12, "sssp", 64),
        ("Failure bottleneck", b12, "bottleneck", 64),
        ("Extreme SSSP", b06, "sssp", 512),
        ("Extreme bottleneck", b13, "bottleneck", 1024),
    ]:
        for model in ["DeltaNAR", "Recompute"]:
            if model not in data.get(task, {}) or str(n) not in data[task][model]:
                continue
            ood_rows_md.append(
                [
                    setting,
                    MODEL_LABEL[model].replace(r"\deltanar", "DeltaNAR"),
                    str(n),
                    md_pm(data, task, model, n, "node_acc_v"),
                    md_pm(data, task, model, n, "graph_acc_v"),
                    md_pm(data, task, model, n, "aff_f1"),
                ]
            )
            ood_rows_tex.append(
                [
                    setting,
                    MODEL_LABEL[model],
                    str(n),
                    pm(data, task, model, n, "node_acc_v"),
                    pm(data, task, model, n, "graph_acc_v"),
                    pm(data, task, model, n, "aff_f1"),
                ]
            )
    md.append("## OOD and Extreme Stress Tests\n")
    md.append(md_table(["Setting", "Model", "n", "node", "graph", "aff_f1"], ood_rows_md))
    md.append("")
    tex.append(r"\newcommand{\BServerStressRows}{%")
    tex.append(latex_rows(ood_rows_tex))
    tex.append("}")

    return "\n".join(md) + "\n", "\n".join(tex) + "\n"


def main() -> None:
    md, tex = build()
    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text(md, encoding="utf-8")
    OUT_TEX.write_text(tex, encoding="utf-8")
    print(f"wrote {OUT_MD}")
    print(f"wrote {OUT_TEX}")


if __name__ == "__main__":
    main()
