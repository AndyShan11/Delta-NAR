"""Write LaTeX table macros for C34/C35/C38 server results."""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
TABLES = ROOT / "paper" / "tables"


def load(name: str) -> dict:
    with (ROOT / "results" / name).open("r", encoding="utf-8") as f:
        return json.load(f)


def metric(data: dict, task: str, model: str, size: str, key: str) -> list[float]:
    return data["agg"][task][model][size][key]


def prof(data: dict, variant: str, task: str, size: str, key: str) -> list[float]:
    return data["agg"][variant][task][size][key]


def pm(pair: list[float], digits: int = 3) -> str:
    return f"{pair[0]:.{digits}f} $\\pm$ {pair[1]:.{digits}f}"


def write_c34_c35() -> None:
    c34_c3 = load("C34_36h_c3_size_20seed_merged.json")
    c34_c4 = load("C34_36h_c4_wide_20seed_merged.json")
    c35_c3 = load("C35_36h_c3_size_repaironly_20seed_merged.json")
    c35_c4 = load("C35_36h_c4_wide_repaironly_20seed_merged.json")
    rows = []
    specs = [
        ("Size", c34_c3, c35_c3, ["256", "512"]),
        ("Wide", c34_c4, c35_c4, ["64", "128", "256"]),
    ]
    model_safe = "DeltaNAR+copy-safe repair"
    model_repair = "DeltaNAR+repair-only"
    for setting, safe, repair, sizes in specs:
        for task, label in [("sssp", "SSSP"), ("bottleneck", "Bottleneck")]:
            for size in sizes:
                for model_label, data, model in [
                    ("copy-safe", safe, model_safe),
                    ("repair-only", repair, model_repair),
                ]:
                    rows.append(
                        [
                            setting,
                            label,
                            size,
                            model_label,
                            pm(metric(data, task, model, size, "node_acc_v")),
                            pm(metric(data, task, model, size, "changed_output_acc_v")),
                            pm(metric(data, task, model, size, "copy_critical_acc_v")),
                            pm(metric(data, task, model, size, "graph_acc_v")),
                        ]
                    )

    lines = [
        "% Auto-generated by write_c34538_tables.py; do not edit numbers by hand.",
        r"\newcommand{\CStressRepairRows}{%",
    ]
    for row in rows:
        lines.append(" & ".join(row) + r" \\")
    lines.append("}")
    (TABLES / "c34538_stress_repair_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_c38() -> None:
    data = load("C38_efficiency_10seed_merged.json")
    rows = []
    for task, label in [("sssp", "SSSP"), ("bottleneck", "Bottleneck")]:
        for size in ["64", "128", "256", "512"]:
            rows.append(
                [
                    label,
                    size,
                    pm(prof(data, "copy_safe", task, size, "eval_seconds"), 1),
                    pm(prof(data, "copy_safe", task, size, "peak_memory_mb"), 1),
                    pm(prof(data, "copy_safe", task, size, "eval_samples_per_sec"), 2),
                    pm(prof(data, "copy_safe", task, size, "node_acc_v")),
                ]
            )

    lines = [
        "% Auto-generated by write_c34538_tables.py; do not edit numbers by hand.",
        r"\newcommand{\CEfficiencyRows}{%",
    ]
    for row in rows:
        lines.append(" & ".join(row) + r" \\")
    lines.append("}")
    (TABLES / "c38_efficiency_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    TABLES.mkdir(parents=True, exist_ok=True)
    write_c34_c35()
    write_c38()
    print(f"wrote {TABLES / 'c34538_stress_repair_numbers.tex'}")
    print(f"wrote {TABLES / 'c38_efficiency_numbers.tex'}")


if __name__ == "__main__":
    main()
