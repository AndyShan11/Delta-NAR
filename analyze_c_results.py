"""Summarize C-line weight-OOD results.

The C-line stress tests evaluate SSSP under weight-distribution shift. This
script gathers the normal ER baseline and the two C-line JSON artifacts into a
single machine-readable summary plus a LaTeX table macro.
"""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results"
OUT_JSON = RESULTS / "C_weight_ood_summary.json"
OUT_MD = ROOT / "C_RESULTS_SUMMARY.md"
OUT_TEX = ROOT / "paper" / "tables" / "c_weight_ood_numbers.tex"


SOURCES = {
    "normal": "A_sssp.json",
    "wide": "C_sssp_whi100.json",
    "heavy": "C_sssp_heavy.json",
}


def load_metric(source: str, model: str, metric: str = "node_acc_v") -> list[float]:
    with (RESULTS / source).open("r", encoding="utf-8") as f:
        data = json.load(f)
    return data["agg"]["sssp"][model]["64"][metric]


def pm(pair: list[float]) -> str:
    return f"{pair[0]:.3f} +/- {pair[1]:.3f}"


def tex_pm(pair: list[float]) -> str:
    return f"{pair[0]:.3f} $\\pm$ {pair[1]:.3f}"


def main() -> None:
    summary = {
        "sources": SOURCES,
        "task": "sssp",
        "size": 64,
        "metric": "node_acc_v",
        "agg": {},
    }
    for model in ["DeltaNAR", "Recompute"]:
        summary["agg"][model] = {
            setting: load_metric(source, model)
            for setting, source in SOURCES.items()
        }

    OUT_JSON.write_text(json.dumps(summary, indent=2), encoding="utf-8")

    lines = [
        "# C-Line Weight-OOD Summary\n",
        "SSSP weight-distribution stress tests at n=64, metric `node_acc_v`. "
        "Values are mean +/- population std over stored seeds.\n",
        "| Model | normal w<=10 | wide w<=100 | heavy-tail |",
        "|---|---:|---:|---:|",
    ]
    for model in ["DeltaNAR", "Recompute"]:
        cells = [pm(summary["agg"][model][setting]) for setting in ["normal", "wide", "heavy"]]
        lines.append(f"| {model} | " + " | ".join(cells) + " |")
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")

    tex = [
        "% Auto-generated by analyze_c_results.py; do not edit numbers by hand.",
        r"\newcommand{\CWeightOODRows}{%",
    ]
    labels = {"DeltaNAR": r"\deltanar", "Recompute": "Recompute"}
    for model in ["DeltaNAR", "Recompute"]:
        cells = [tex_pm(summary["agg"][model][setting]) for setting in ["normal", "wide", "heavy"]]
        tex.append(labels[model] + " & " + " & ".join(cells) + r" \\")
    tex.append("}")
    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
    OUT_TEX.write_text("\n".join(tex) + "\n", encoding="utf-8")

    print(f"wrote {OUT_JSON}")
    print(f"wrote {OUT_MD}")
    print(f"wrote {OUT_TEX}")


if __name__ == "__main__":
    main()
