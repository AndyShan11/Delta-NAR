"""Summarize local hard-repair A-line diagnostics.

These runs intentionally make the edit larger than the default single-edit
setting. They are not meant to replace the server B-line headline numbers; they
serve as a targeted stress test for copy dominance and repair quality.
"""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results"
OUT_MD = ROOT / "A_HARD_REPAIR_AUDIT.md"
OUT_TEX = ROOT / "paper" / "tables" / "a_hard_repair_numbers.tex"


def load(name: str, task: str) -> dict:
    with (RESULTS / name).open("r", encoding="utf-8") as f:
        return json.load(f)["agg"][task]


def pm(data: dict, model: str, size: int, metric: str) -> str:
    m, s = data[model][str(size)][metric]
    return f"{m:.3f} $\\pm$ {s:.3f}"


def md_pm(data: dict, model: str, size: int, metric: str) -> str:
    m, s = data[model][str(size)][metric]
    return f"{m:.3f} +/- {s:.3f}"


def md_table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |"]
    lines.append("| " + " | ".join(["---"] * len(headers)) + " |")
    lines.extend("| " + " | ".join(r) + " |" for r in rows)
    return "\n".join(lines)


def build() -> tuple[str, str]:
    tasks = [
        (
            "SSSP",
            "sssp",
            load("AHR_sssp_train4_test12_3seed.json", "sssp"),
            load("AHR_oracle_sssp_train4_test12_3seed.json", "sssp"),
            load("AHR_sssp_train12_test12_3seed.json", "sssp"),
        ),
        (
            "Bottleneck",
            "bottleneck",
            load("AHR_bottleneck_train4_test12_3seed.json", "bottleneck"),
            load("AHR_oracle_bottleneck_train4_test12_3seed.json", "bottleneck"),
            load("AHR_bottleneck_train12_test12_3seed.json", "bottleneck"),
        ),
    ]
    sizes = [16, 32, 64]

    md: list[str] = [
        "# A Hard-Repair Local Audit\n",
        "Configuration: SSSP, train with 4 simultaneous edits, test with 12 "
        "simultaneous edits, 3 seeds, train_n=16, sizes 16/32/64. This is a "
        "local stress test for repair quality rather than a headline server "
        "result.\n",
    ]
    tex: list[str] = ["% Auto-generated by analyze_ahr_results.py; do not edit numbers by hand."]

    model_rows_md: list[list[str]] = []
    model_rows_tex: list[list[str]] = []
    for task_label, _, hard, _, _ in tasks:
        for model, label in [
            ("DeltaNAR", r"\deltanar"),
            ("no-copy", "no-copy"),
            ("Naive-d", "Prev+Delta"),
            ("Recompute", "Recompute"),
        ]:
            model_rows_md.append(
                [
                    task_label,
                    label.replace(r"\deltanar", "DeltaNAR"),
                    md_pm(hard, model, 64, "node_acc_v"),
                    md_pm(hard, model, 64, "graph_acc_v"),
                    md_pm(hard, model, 64, "changed_output_acc_v"),
                    md_pm(hard, model, 64, "copy_critical_acc_v"),
                ]
            )
            model_rows_tex.append(
                [
                    task_label,
                    label,
                    pm(hard, model, 64, "node_acc_v"),
                    pm(hard, model, 64, "graph_acc_v"),
                    pm(hard, model, 64, "changed_output_acc_v"),
                    pm(hard, model, 64, "copy_critical_acc_v"),
                ]
            )
    md.append("## Hard-Repair Models at n=64\n")
    md.append(md_table(["Task", "Model", "node", "graph", "changed", "copy-critical"], model_rows_md))
    md.append("")
    tex.append(r"\newcommand{\AHRModelRows}{%")
    tex.extend(" & ".join(r) + r" \\" for r in model_rows_tex)
    tex.append("}")

    oracle_rows_md: list[list[str]] = []
    oracle_rows_tex: list[list[str]] = []
    for task_label, _, _, oracle, _ in tasks:
        for variant, label in [
            ("raw_no_copy", "raw no-copy"),
            ("predicted_copy", "predicted copy"),
            ("oracle_affected_copy", "oracle affected copy"),
            ("oracle_copy_safe_upper", "oracle copy-safe upper"),
            ("pure_copy", "pure copy"),
        ]:
            oracle_rows_md.append(
                [
                    task_label,
                    label,
                    md_pm(oracle, variant, 64, "node_acc_v"),
                    md_pm(oracle, variant, 64, "graph_acc_v"),
                    md_pm(oracle, variant, 64, "changed_output_acc_v"),
                    md_pm(oracle, variant, 64, "copy_critical_acc_v"),
                ]
            )
            oracle_rows_tex.append(
                [
                    task_label,
                    label,
                    pm(oracle, variant, 64, "node_acc_v"),
                    pm(oracle, variant, 64, "graph_acc_v"),
                    pm(oracle, variant, 64, "changed_output_acc_v"),
                    pm(oracle, variant, 64, "copy_critical_acc_v"),
                ]
            )
    md.append("## Oracle Decomposition at n=64\n")
    md.append(md_table(["Task", "Variant", "node", "graph", "changed", "copy-critical"], oracle_rows_md))
    md.append("")
    tex.append(r"\newcommand{\AHROracleRows}{%")
    tex.extend(" & ".join(r) + r" \\" for r in oracle_rows_tex)
    tex.append("}")

    frac_rows = []
    for task_label, _, hard, _, _ in tasks:
        for n in sizes:
            frac_rows.append(
                [
                    task_label,
                    str(n),
                    md_pm(hard, "DeltaNAR", n, "affected_fraction"),
                    md_pm(hard, "DeltaNAR", n, "changed_output_fraction"),
                    md_pm(hard, "DeltaNAR", n, "copy_critical_fraction"),
                ]
            )
    md.append("## Region Fractions\n")
    md.append(md_table(["Task", "n", "affected", "changed-output", "copy-critical"], frac_rows))
    md.append("")

    matched_rows_md: list[list[str]] = []
    matched_rows_tex: list[list[str]] = []
    for task_label, _, train4, _, train12 in tasks:
        for setting, data in [("train4/test12", train4), ("train12/test12", train12)]:
            matched_rows_md.append(
                [
                    task_label,
                    setting,
                    md_pm(data, "DeltaNAR", 64, "node_acc_v"),
                    md_pm(data, "DeltaNAR", 64, "graph_acc_v"),
                    md_pm(data, "DeltaNAR", 64, "changed_output_acc_v"),
                    md_pm(data, "DeltaNAR", 64, "copy_critical_acc_v"),
                    md_pm(data, "DeltaNAR", 64, "gate_recall"),
                ]
            )
            matched_rows_tex.append(
                [
                    task_label,
                    setting,
                    pm(data, "DeltaNAR", 64, "node_acc_v"),
                    pm(data, "DeltaNAR", 64, "graph_acc_v"),
                    pm(data, "DeltaNAR", 64, "changed_output_acc_v"),
                    pm(data, "DeltaNAR", 64, "copy_critical_acc_v"),
                    pm(data, "DeltaNAR", 64, "gate_recall"),
                ]
            )
    md.append("## Matched-Hard Training Check at n=64\n")
    md.append(md_table(["Task", "Setting", "node", "graph", "changed", "copy-critical", "gate recall"], matched_rows_md))
    md.append("")
    tex.append(r"\newcommand{\AHRMatchedRows}{%")
    tex.extend(" & ".join(r) + r" \\" for r in matched_rows_tex)
    tex.append("}")
    md.append(
        "\nInterpretation: SSSP keeps a clear full-node and graph advantage under "
        "this harder setting, while bottleneck exposes the current repair weakness "
        "more sharply. Predicted copy is often much closer to affected-oracle copy "
        "than to copy-safe oracle. Training directly on twelve-edit updates does "
        "not fix the changed-output weakness, so the next target is architectural: "
        "copy-safety calibration and a stronger local repair branch.\n"
    )

    return "\n".join(md) + "\n", "\n".join(tex) + "\n"


def main() -> None:
    md, tex = build()
    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text(md, encoding="utf-8")
    OUT_TEX.write_text(tex, encoding="utf-8")
    print(f"wrote {OUT_MD}")
    print(f"wrote {OUT_TEX}")


if __name__ == "__main__":
    main()
