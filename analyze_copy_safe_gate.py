"""Summarize independent copy-safe gate AHR experiments."""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results"
OUT = ROOT / "COPY_SAFE_GATE_EXPERIMENTS.md"
OUT_TEX = ROOT / "paper" / "tables" / "copy_safe_gate_numbers.tex"


def load(path: str, task: str, model: str) -> dict:
    with (RESULTS / path).open("r", encoding="utf-8") as f:
        return json.load(f)["agg"][task][model]["64"]


def pm(d: dict, metric: str) -> str:
    return f"{d[metric][0]:.3f} +/- {d[metric][1]:.3f}"


def tex_pm(d: dict, metric: str) -> str:
    return f"{d[metric][0]:.3f} $\\pm$ {d[metric][1]:.3f}"


def main() -> None:
    rows = []
    for label, task in [("SSSP", "sssp"), ("Bottleneck", "bottleneck")]:
        base = load(f"AHR_{task}_train4_test12_3seed.json", task, "DeltaNAR")
        safe = load(f"AHR_copysafegate_{task}_3seed.json", task, "DeltaNAR+repair")
        for variant, data in [("baseline", base), ("copy-safe gate", safe)]:
            rows.append(
                [
                    label,
                    variant,
                    pm(data, "node_acc_v"),
                    pm(data, "graph_acc_v"),
                    pm(data, "changed_output_acc_v"),
                    pm(data, "copy_critical_acc_v"),
                    pm(data, "gate_recall"),
                ]
            )
    tex_rows = []
    for label, task in [("SSSP", "sssp"), ("Bottleneck", "bottleneck")]:
        base = load(f"AHR_{task}_train4_test12_3seed.json", task, "DeltaNAR")
        safe = load(f"AHR_copysafegate_{task}_3seed.json", task, "DeltaNAR+repair")
        for variant, data in [("baseline", base), ("copy-safe gate", safe)]:
            tex_rows.append(
                [
                    label,
                    variant,
                    tex_pm(data, "node_acc_v"),
                    tex_pm(data, "graph_acc_v"),
                    tex_pm(data, "changed_output_acc_v"),
                    tex_pm(data, "copy_critical_acc_v"),
                    tex_pm(data, "gate_recall"),
                ]
            )
    lines = [
        "# Copy-Safe Gate Experiments\n",
        "Local AHR 3-seed experiments with train_delta_size=4, test_delta_size=12, "
        "train_n=16, n=64. The independent copy-safe gate was then validated by "
        "the C2 20-seed server rerun summarized in `C2_COPYSAFE_SERVER_SUMMARY.md`.\n",
        "| Task | Variant | node | graph | changed | copy-critical | gate recall |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    lines.append(
        "\nInterpretation: copy-safe gating is the first structured local change "
        "that materially improves the hard-repair bottleneck setting. On SSSP it "
        "raises changed-output repair but hurts graph accuracy; the C2 full-budget "
        "20-seed rerun keeps SSSP node accuracy stable and raises repair slices. "
        "On bottleneck, C2 reaches `0.916 +/- 0.092` node, `0.271 +/- 0.184` "
        "graph, `0.663 +/- 0.053` changed-output, and `0.746 +/- 0.039` "
        "copy-critical accuracy at `n=64`, making copy-safety calibration the "
        "strongest current architectural improvement."
    )
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    tex = [
        "% Auto-generated by analyze_copy_safe_gate.py; do not edit numbers by hand.",
        r"\newcommand{\CopySafeGateRows}{%",
    ]
    for row in tex_rows:
        tex.append(" & ".join(row) + r" \\")
    tex.append("}")
    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
    OUT_TEX.write_text("\n".join(tex) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    print(f"wrote {OUT_TEX}")


if __name__ == "__main__":
    main()
